import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import { homedir } from 'node:os';
import { existsSync } from 'node:fs';
const exe=['AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe','AppData/Local/ms-playwright/chromium-1200/chrome-win64/chrome.exe'].map(x=>homedir()+'/'+x).find(existsSync);
const srv = spawn('npx',['vite','preview','--port','4176','--strictPort','--host','127.0.0.1'],{stdio:'ignore',shell:true});
await new Promise(r=>setTimeout(r,2500));
const b = await chromium.launch({ executablePath:exe, headless:true });
const p = await b.newPage({viewport:{width:1440,height:900}});
await p.goto('http://127.0.0.1:4176/');
await p.waitForTimeout(1200);
const info = await p.evaluate(()=>{
  const btn=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='点火');
  const r=btn.getBoundingClientRect();
  const top=document.elementFromPoint(r.x+r.width/2, r.y+r.height/2);
  return {rect:{x:r.x,y:r.y,w:r.width,h:r.height}, top: top? top.className+'|'+top.tagName : 'none', btns:[...document.querySelectorAll('button')].map(x=>x.textContent.trim())};
});
console.log(JSON.stringify(info,null,2));
await p.screenshot({path:'/tmp/dbg.png'});
await b.close(); srv.kill();
