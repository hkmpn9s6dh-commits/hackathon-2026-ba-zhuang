import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import { homedir } from 'node:os';
import { existsSync } from 'node:fs';
const exe=['AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe','AppData/Local/ms-playwright/chromium-1200/chrome-win64/chrome.exe'].map(x=>homedir()+'/'+x).find(existsSync);
const srv = spawn('npx',['vite','preview','--port','4177','--strictPort','--host','127.0.0.1'],{stdio:'ignore',shell:true});
await new Promise(r=>setTimeout(r,2500));
const b = await chromium.launch({ executablePath:exe, headless:true });
const p = await b.newPage({viewport:{width:1440,height:900}, deviceScaleFactor:3});
await p.goto('http://127.0.0.1:4177/');
await p.waitForTimeout(800);
await p.click('.btn-primary'); await p.waitForTimeout(300);
await p.click('.panel .btn-primary'); await p.waitForTimeout(400);
const card = p.locator('.card').first();
await card.screenshot({path:'/tmp/card.png'});
const dims = await p.evaluate(()=>{const c=document.querySelector('.card canvas'); const r=c.getBoundingClientRect(); return {cw:c.clientWidth, ch:c.clientHeight, attrw:c.width, attrh:c.height, rect:{w:r.width,h:r.height}};});
console.log(JSON.stringify(dims));
await b.close(); srv.kill();
