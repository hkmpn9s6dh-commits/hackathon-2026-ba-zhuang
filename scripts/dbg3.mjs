import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import { homedir } from 'node:os';
import { existsSync } from 'node:fs';
const exe=['AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe','AppData/Local/ms-playwright/chromium-1200/chrome-win64/chrome.exe'].map(x=>homedir()+'/'+x).find(existsSync);
const srv = spawn('npx',['vite','preview','--port','4178','--strictPort','--host','127.0.0.1'],{stdio:'ignore',shell:true});
await new Promise(r=>setTimeout(r,2400));
const b = await chromium.launch({ executablePath:exe, headless:true });
const p = await b.newPage({viewport:{width:1440,height:900}, deviceScaleFactor:2});
await p.goto('http://127.0.0.1:4178/');
await p.waitForTimeout(700);
await p.click('.btn-primary'); await p.waitForTimeout(250);
await p.click('.panel .btn-primary'); await p.waitForTimeout(400);
await p.evaluate(()=>window.__game.game.autoPlace());
await p.waitForTimeout(300);
await p.screenshot({path:'proof/shots/zoom-load.png', clip:{x:600,y:100,width:700,height:560}});
await p.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='封窑'); b&&b.click();});
await p.waitForTimeout(300);
await p.evaluate(()=>{const g=window.__game.game; for(let t=0;t<130;t+=0.05){const gap=g.target-g.state.fire.temp; g.setVent(gap>0.12?3:gap>0.04?2:gap>0.005?1:0); g.feed(gap>0.002); g.update(0.05); if(g.state.event||g.state.shard) break;}});
await p.waitForTimeout(600);
await p.screenshot({path:'proof/shots/zoom-fire.png', clip:{x:420,y:60,width:880,height:620}});
const card = p.locator('.tray .card').first();
if (await card.count()) await card.screenshot({path:'proof/shots/zoom-card.png'});
await b.close(); srv.kill();
